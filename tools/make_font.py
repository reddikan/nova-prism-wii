#!/usr/bin/env python3
"""Bakes the handwriting font (Gloria Hallelujah, SIL Open Font License - see tools/fonts/OFL.txt)
into source/font_data.h: greyscale atlases (stored 4 bits per pixel) plus glyph metrics - a small one for
small text and a big one so large lettering stays crisp.
Only needed when changing the font:  python3 tools/make_font.py"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))

def bake(bake, W, H):
    font = ImageFont.truetype(os.path.join(HERE, "fonts", "GloriaHallelujah.ttf"), bake)
    atlas = Image.new("L", (W, H), 0)
    pad = max(3, bake // 12)
    x, y, row_h = pad, pad, 0
    metrics = []
    for code in range(32, 127):
        ch = chr(code)
        adv = font.getlength(ch)
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        if w == 0 or h == 0:
            metrics.append((0, 0, 0, 0, 0, 0, adv)); continue
        if x + w + pad > W:
            x, y, row_h = pad, y + row_h + pad, 0
        assert y + h + pad <= H, "atlas full"
        img = Image.new("L", (w + 2, h + 2), 0)
        ImageDraw.Draw(img).text((1 - l, 1 - t), ch, font=font, fill=255, anchor="ls")
        atlas.paste(img, (x - 1, y - 1))
        metrics.append((x, y, w, h, l, t, adv))
        x += w + pad
        row_h = max(row_h, h)
    print("baked %dpx: rows used up to y = %d of %d" % (bake, y + row_h, H))
    px = atlas.tobytes()
    return metrics, bytes(((px[i] >> 4) << 4) | (px[i + 1] >> 4) for i in range(0, len(px), 2))


SETS = [("FONT", 38, 512, 256),       # small text
        ("FONTB", 96, 1024, 672)]     # big text, so titles and banners stay crisp
out = os.path.join(HERE, "..", "source", "font_data.h")
with open(out, "w") as f:
    f.write("/* Generated by tools/make_font.py - Gloria Hallelujah by Kimberly Geswein, SIL Open Font License 1.1 */\n")
    for name, size, W, H in SETS:
        metrics, packed = bake(size, W, H)
        f.write("#define %s_BAKE %d\n#define %s_W %d\n#define %s_H %d\n" % (name, size, name, W, name, H))
        f.write("/* x, y, w, h, left bearing, top (relative to the baseline), advance */\n")
        f.write("static const short %s_METRICS[95][7] = {\n" % name)
        for m in metrics:
            f.write("    {%d,%d,%d,%d,%d,%d,%d},\n" % (m[0], m[1], m[2], m[3], m[4], m[5], round(m[6])))
        f.write("};\n/* 4-bit greyscale, two pixels per byte (high nibble first) */\n")
        f.write("static const unsigned char %s_PIXELS[%d] = {\n" % (name, len(packed)))
        for i in range(0, len(packed), 32):
            f.write("    " + ",".join(str(v) for v in packed[i:i + 32]) + ",\n")
        f.write("};\n")
